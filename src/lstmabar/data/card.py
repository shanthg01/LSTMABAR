def _fmt(x: Any) -> str:
    if isinstance(x, float):
        return f"{x:.4g}" if abs(x) < 1e4 else f"{x:.0f}"
    return str(x)


def _table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(_fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def _counts_table(title: str, counts: Mapping[str, int]) -> str:
    total = sum(counts.values())
    rows = [[k, v, f"{100 * v / total:.1f} %" if total else "-"] for k, v in counts.items()]
    return _table([title, "count", "share"], rows)


def _cross_table(first: str, nested: Mapping[str, Mapping[str, int]]) -> str:
    cols = sorted({c for row in nested.values() for c in row})
    rows = [[k, *[row.get(c, 0) for c in cols]] for k, row in nested.items()]
    return _table([first, *cols], rows)


_STATS = ("n", "min", "p05", "median", "p95", "max", "mean")


def _summary_table(first: str, summaries: Mapping[str, Mapping[str, Any]]) -> str:
    rows = [[k, *[s.get(c, "-") for c in _STATS]] for k, s in summaries.items()]
    return _table([first, *_STATS], rows)


def _sections(ix: Mapping[str, Any]) -> dict[str, str]:
    clips, items, caps = ix["clips"], ix["items"], ix["captions"]
    status = (
        f"**Frozen.** Schema version {ix['schema_version']}, dataset SHA-256 "
        f"`{ix['dataset_sha256']}`, built at commit `{ix.get('git_sha') or 'unknown'}`."
    )
    if ix.get("partial"):
        status += (
            f"\n\n**PARTIAL freeze**: {len(ix['skipped_shards'])} unfinished shards were "
            "skipped (`--allow-partial`); not a release."
        )
    summary = "\n\n".join(
        [
            f"{items['total']} rendered items from {clips['total']} dry clips, with "
            f"{caps['total']} captions. Holdout pedal: `{ix.get('holdout_pedal')}`.",
            _counts_table("split (items)", items["by_split"]),
            _counts_table("scenario", items["by_scenario"]),
            _counts_table("engine", items["by_engine"]),
            _cross_table("split \\ pedal or free scenario", items["by_split_pedal"]),
        ]
    )
    splits = "\n\n".join(
        [
            _cross_table("performer \\ split (clips)", clips["by_performer_split"]),
            _table(
                ["split", "clips", "recordings"],
                [
                    [s, n, clips["recordings_by_split"].get(s, 0)]
                    for s, n in clips["by_split"].items()
                ],
            ),
            "Performers in more than one split: "
            + (
                ", ".join(f"{p} ({', '.join(s)})" for p, s in clips["performer_overlap"].items())
                or "none"
            )
            + ".",
        ]
    )
    levels = "\n\n".join(
        [
            _summary_table(
                "quantity",
                {
                    "input_peak_dbfs": items["input_peak_dbfs"],
                    "wet_gain_db": items["wet_gain_db"],
                    "clip duration_s": clips["duration_s"],
                    "renders per clip": items["renders_per_clip"],
                },
            )
        ]
    )
    lc = items["clamped"]
    labels = "\n\n".join(
        [
            _counts_table("label source", items["by_label_source"]),
            f"Clamped derived labels: {lc['total']} items "
            f"({', '.join(f'{k}: {v}' for k, v in lc['by_pedal'].items()) or 'none'}). "
            f"Calibrated labels with clamp notes: {items['label_clamped']['total']}. "
            f"Nearest-grid-point fallbacks: {items['calibrated_nearest']['total']} "
            f"({', '.join(f'{k}: {v}' for k, v in items['calibrated_nearest']['by_pedal'].items()) or 'none'}).",  # noqa: E501
            "Disabled blocks in free-board items (knob values there are random; mask by "
            "`enabled`):",
            _cross_table("scenario \\ disabled block", items["free_board_disabled_blocks"])
            if items["free_board_disabled_blocks"]
            else "none",
        ]
    )
    v = ix["voicing"]
    models = ", ".join(f"`{m}` ({n})" for m, n in caps["models"].items()) or "none"
    captions = "\n\n".join(
        [
            _counts_table("caption kind", caps["by_kind"]),
            _counts_table("split (captions)", caps["by_split"]),
            f"Paraphrase model / prompt version: {models}. Captions naming a pedal: "
            f"{caps['names_pedal']}. Items with only template captions (paraphrase rejected, "
            f"malformed or not run): {caps['items_template_only']}; items with fewer than "
            f"{caps['paraphrases_per_item']} paraphrases: {caps['items_missing_paraphrases']}.",
            f"Voiced fraction of the dry clips' pitch tracks ({v['clips_with_items']} clips): "
            f"{v['below_min']} below {v['min_voiced_fraction']} (harmonic descriptors not "
            f"measured), {v['not_measured']} without a track.",
            _summary_table("voiced fraction", {"dry clips": v["voiced_fraction"]}),
        ]
    )
    performers = "\n\n".join(
        [
            "Source gain applied to reach the stored −1 dBFS peak (dB), per performer:",
            _summary_table("performer", clips["source_gain_db_by_performer"]),
            "Clip RMS at the source level (dBFS), per performer:",
            _summary_table("performer", clips["source_rms_dbfs_by_performer"]),
        ]
    )
    tr = ix.get("test_real")
    if tr is None:
        test_real = "No `test_real` manifest at freeze time."
    else:
        test_real = "\n\n".join(
            [
                f"`test_real`: {tr['total']} items, {tr['internal_only']} internal only "
                f"(never published). Sample rates: "
                + ", ".join(f"{k} Hz ({n})" for k, n in tr["sample_rates"].items())
                + ".",
                _counts_table("dataset / device", tr["by_device"]),
            ]
        )
    integrity = "\n\n".join(
        [
            f"{ix['files']['count']} audio files hashed in `files.sha256` (dry + wet; "
            "`test_real` file hashes live in `test_real.jsonl`). Manifests:",
            _table(
                ["manifest", "sha256"], [[k, f"`{h}`"] for k, h in ix["files"]["manifests"].items()]
            ),
        ]
    )
    return {
        "version": ix["version"],
        "status": status,
        "summary": summary,
        "splits": splits,
        "levels": levels,
        "labels": labels,
        "captions": captions,
        "performers": performers,
        "test_real": test_real,
        "integrity": integrity,
    }


def render_data_card(index: Mapping[str, Any] | None, version: str = "v1") -> str:
    """The data card for ``index`` (``None``: not frozen yet)."""
    if index is None:
        keys = ("summary", "splits", "levels", "labels", "captions", "performers")
        values = dict.fromkeys(keys, PENDING)
        values |= {
            "version": version,
            "status": "**Not frozen yet.** Numbers below are filled in by the freeze.",
            "test_real": PENDING,
            "integrity": PENDING,
        }
    else:
        values = _sections(index)
    text = TEMPLATE.substitute(values)
    return "\n".join(line.rstrip() for line in text.splitlines()) + "\n"


