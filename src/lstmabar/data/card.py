"""``DATA_CARD.md``: hand-written prose + numbers generated from the dataset index (task 4.6).

:func:`render_data_card` fills :data:`TEMPLATE` (``string.Template``, ``$name`` placeholders)
from ``DataLayout.index``. Every number in the card comes from the index; none is typed by
hand. With ``index=None`` the numeric sections say the dataset is not frozen yet (the card
committed before the first freeze). ``lstmabar data freeze`` regenerates the card, and
``tests/data/test_leakage.py`` checks the committed card matches the committed index.
"""

